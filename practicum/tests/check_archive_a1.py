"""Прогоняет архивный ноутбук A1 целиком: пустым, с эталонами и с ошибками.

Устроен так же, как check_archive_c2.py, и по той же причине: в архивном
ноутбуке нет ни одного разбора, который проверялся бы отдельно, — вся
его правильность в том, что ответ из раздела Solutions проходит проверку
в ячейке. Тест берёт сам ноутбук, подставляет в каждый placeholder эталон
из ANSWERS генератора и требует, чтобы каждая проверка сказала ✅.

Заодно проверяется главное свойство формата: пустой ноутбук проходится
сверху вниз без единого исключения и печатает ⬜. Без этого его нельзя
залить на Kaggle, где ячейки исполняются автоматически.

Эталоны в ANSWERS взяты из markschemes, и здесь не записан ни один из
них: проверкам передаётся правило — первый член и шаг, — а член и сумма
получаются сложением. Формулы u₁ + (n − 1)d у них нет. Совпадение
в этом тесте поэтому означает согласие markscheme с самим сложением,
а не с моей записью, — пятьдесят семь раз подряд.

Число проверок и число ответов здесь не совпадают, и это не сбой.
У 1.1 и 1.3 ответа два, а проверка одна: только одна пара u₁ и d
воспроизводит 15 − 3n, и порознь их не разделить. У 8.1 и 8.2 то же
самое — три ответа на две проверки и два на одну. А у 2.6, 5.5, 6.7,
6.9, 8.3 и 9.2 наоборот: один placeholder, а проверок на нём несколько,
и в 8.3 их четыре, потому что функций две. Разница считается один раз
и сверяется числом.

Третий прогон: каждый ответ по очереди заменяется типовой ошибкой —
номер сдвинут на единицу, знак разности противоположный, сумма оборвана
на член раньше, — и проверка обязана сказать ❌. BREAK держит ошибку
для каждого из пятидесяти семи ответов.

Запуск:  python practicum/tests/check_archive_a1.py
"""
