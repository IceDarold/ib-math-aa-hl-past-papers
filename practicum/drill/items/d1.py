"""Задачи на счёт для практикума D1: комбинаторика.

Тема — одно решение, принятое по-разному: повторяются ли объекты и
считается ли их порядок. Генераторы держатся того же разреза, что и
лестница: первые три — три ответа на это решение, четвёртый и пятый —
ограничение «вместе» и его дополнение, шестой складывает случаи,
седьмой ставит букву внутрь счёта.

Ответ здесь всегда целое число, и `count_check` присылать его нельзя:
он кладёт число в задание открытым текстом, а на странице задание видно
целиком. Поэтому все проверки — `num_check(..., sf=6)`: на странице
остаётся хеш, а шесть значащих цифр делают сверку точной для всего,
что меньше миллиона, и совпадают с тем, что принимает схема оценивания
у чисел покрупнее (645000 вместо 645120, 12400000 вместо 12441600).

Числа подбираются так, чтобы ответ брался с калькулятором за один шаг,
а не был упражнением в арифметике: тренируется решение о том, что
считать, а не умножение в столбик.
"""
from __future__ import annotations

from math import comb, factorial, perm

from .common import num_check

# Имя после числа склоняется по числу, и у каждого существительного свои
# три формы. Общей на всех не бывает: «7 участника» и «11 музыканта» —
# ровно та же ошибка, что «6 красных и 1 белых шар» в генераторах D2.
PEOPLE = [
    ('ученик', 'ученика', 'учеников'),
    ('спортсмен', 'спортсмена', 'спортсменов'),
    ('музыкант', 'музыканта', 'музыкантов'),
    ('участник', 'участника', 'участников'),
]
PERSON = ('человек', 'человека', 'человек')
GIRL = ('девочка', 'девочки', 'девочек')
BOY = ('мальчик', 'мальчика', 'мальчиков')
BOOK = ('книга', 'книги', 'книг')
SEAT = ('место', 'места', 'мест')
TEAM = ('команда', 'команды', 'команд')


def _form(count, forms):
    """Форма существительного после числа: 1 ученик, 2 ученика, 5 учеников."""
    one, few, many = forms
    tail = count % 10, count % 100
    if tail[0] == 1 and tail[1] != 11:
        return one
    if tail[0] in (2, 3, 4) and tail[1] not in (12, 13, 14):
        return few
    return many


def _n(count, forms):
    """«$5$ учеников» — число в формуле, существительное в нужной форме."""
    return f'${count}$ {_form(count, forms)}'


def product_rule(rng):
    """Правило произведения: шаги независимы, ничего не кончается."""
    places = rng.choice([3, 4])
    values = rng.choice([4, 5, 6])
    forbid = rng.choice([False, False, True])
    total = values ** places
    if forbid:
        answer = values * (values - 1) * values ** (places - 2)
        tail = (' Первые два знака кода не должны совпадать. ')
    else:
        answer = total
        tail = ' '
    return {
        'prompt': (f'Код состоит из ${places}$ знаков, и каждый знак — '
                   f'одно из ${values}$ значений; значения могут '
                   f'повторяться.{tail}'
                   f'Сколько всего кодов?'),
        'answer': answer,
        'check': num_check(answer, sf=6),
        'budget_ms': 45_000,
        'note': ('Каждый знак выбирается независимо, поэтому числа '
                 'вариантов перемножаются. Ограничение вешается на тот '
                 'шаг, которого оно касается, и только на него: остальные '
                 f'знаки по-прежнему имеют {values} вариантов.'),
    }


def permutation(rng):
    """Размещения: объекты расставляют, каждый берут один раз."""
    total = rng.choice([6, 7, 8, 9])
    kind = rng.choice(['all', 'part', 'restricted'])
    if kind == 'all':
        answer = factorial(total)
        prompt = (f'Сколькими способами можно расставить в ряд '
                  f'${total}$ различных {_form(total, BOOK)}?')
        note = ('Все объекты различны и все расставляются: n!. Порядок '
                'здесь и есть ответ — переставили две книги, получили '
                'другую расстановку.')
    elif kind == 'part':
        take = rng.choice([3, 4])
        answer = perm(total, take)
        prompt = (f'Из ${total}$ различных {_form(total, BOOK)} '
                  f'выбирают ${take}$ и ставят в ряд на полку. Сколькими '
                  f'способами это можно сделать?')
        note = ('Расставляют не все, а часть, и порядок считается: '
                'ⁿPᵣ = n!/(n−r)!. Если бы порядок не считался, ответ был '
                'бы меньше ровно в r! раз.')
    else:
        answer = (total - 1) * perm(total - 1, total - 2)
        prompt = (f'Сколько ${total - 1}$-значных чисел можно составить '
                  f'из цифр $0, 1, \\ldots, {total - 1}$, если все цифры '
                  f'в числе различны?')
        note = ('Ограниченная позиция заполняется первой: старшая цифра '
                'не ноль, у неё n−1 вариантов, а остальные места берут '
                'из всех оставшихся цифр, включая ноль. Оставить эту '
                'позицию напоследок — самый надёжный способ потерять балл.')
    return {
        'prompt': prompt,
        'answer': answer,
        'check': num_check(answer, sf=6),
        'budget_ms': 60_000,
        'note': note,
    }


def combination(rng):
    """Сочетания: группу отбирают, её внутренний порядок ничего не значит."""
    kind = rng.choice(['plain', 'plain', 'teams'])
    if kind == 'plain':
        total = rng.choice([8, 9, 10, 11])
        take = rng.choice([3, 4, 5])
        take = min(take, total - 1)
        answer = comb(total, take)
        who = rng.choice(PEOPLE)
        prompt = (f'Из {_n(total, who)} выбирают {_n(take, who)} '
                  f'в команду. Сколькими способами это можно сделать?')
        note = ('Внутри команды никто ничем не отличается, поэтому каждый '
                'набор посчитан r! раз и на r! делится: ⁿCᵣ = ⁿPᵣ/r!. '
                'Ответ nPr больше верного ровно во столько же раз.')
    else:
        groups = rng.choice([2, 3])
        size = rng.choice([3, 4])
        total = groups * size
        answer = factorial(total)
        for _ in range(groups):
            answer //= factorial(size)
        answer //= factorial(groups)
        who = rng.choice(PEOPLE)
        prompt = (f'{_n(total, who)} делят на ${groups}$ равные '
                  f'{_form(groups, TEAM)} по {_n(size, PERSON)}. Команды '
                  f'никак не названы. Сколькими способами это можно '
                  f'сделать?')
        note = ('Отбирать команды по очереди — значит посчитать каждое '
                f'разбиение {groups}! раз, по разу на порядок, в котором '
                'команды могли появиться. Делить на это число обязательно, '
                'и в схеме оценивания деление — отдельный балл.')
    return {
        'prompt': prompt,
        'answer': answer,
        'check': num_check(answer, sf=6),
        'budget_ms': 60_000,
        'note': note,
    }


def block(rng):
    """Вместе: склеить в один объект и не забыть порядок внутри."""
    total = rng.choice([6, 7, 8])
    glued = rng.choice([2, 3])
    seats = rng.choice([total, total + rng.choice([2, 3])])
    if seats == total:
        answer = factorial(total - glued + 1) * factorial(glued)
        prompt = (f'{_n(total, rng.choice(PEOPLE))} становятся в ряд для '
                  f'фотографии. ${glued}$ из них должны стоять рядом. '
                  f'Сколькими способами их можно расставить?')
        note = (f'Склеенные {_n(glued, PERSON)} — один объект, поэтому '
                f'расставляются {total - glued + 1} объектов, и всё это '
                f'умножается на {glued}! порядков внутри склейки. Именно '
                'этот множитель и теряют.')
    else:
        answer = (seats - total + 1) * factorial(total)
        prompt = (f'В ряду ${seats}$ свободных {_form(seats, SEAT)}. '
                  f'{_n(total, rng.choice(PEOPLE))} садятся так, чтобы '
                  f'занять места подряд. Сколькими способами они могут '
                  f'сесть?')
        note = (f'Блок из {total} мест помещается в ряду из {seats} '
                f'{seats - total + 1} способами, и внутри блока люди '
                f'садятся {total}! способами. Число положений блока — '
                'не факториал; путать их особенно легко, когда они '
                'случайно совпадают.')
    return {
        'prompt': prompt,
        'answer': answer,
        'check': num_check(answer, sf=6),
        'budget_ms': 75_000,
        'note': note,
    }


def complement(rng):
    """Через запрещённое: посчитать всё и вычесть «вместе»."""
    total = rng.choice([5, 6, 7, 8])
    kind = rng.choice(['apart', 'apart', 'symmetry'])
    if kind == 'apart':
        answer = factorial(total) - 2 * factorial(total - 1)
        prompt = (f'{_n(total, rng.choice(PEOPLE))} становятся в ряд. '
                  f'Двое из них поссорились и не должны стоять рядом. '
                  f'Сколькими способами их можно расставить?')
        note = ('«Не рядом» прямым счётом разваливается на случаи, а '
                'дополнением берётся в две строки: всё минус «рядом». '
                'А «рядом» — это склейка, то есть (n−1)! расстановок '
                'на 2 порядка внутри пары.')
    else:
        answer = factorial(total) // 2
        prompt = (f'{_n(total, rng.choice(PEOPLE))} финишируют без '
                  f'одинаковых мест; двое из них — Аня и Борис. Сколько '
                  f'порядков финиша, в которых Аня финиширует раньше '
                  f'Бориса?')
        note = ('У каждого порядка есть зеркальный, где эти двое '
                'переставлены, и ровно в одном из пары первый раньше. '
                'Значит, ответ — половина всех порядков, и никаких '
                'случаев разбирать не надо.')
    return {
        'prompt': prompt,
        'answer': answer,
        'check': num_check(answer, sf=6),
        'budget_ms': 75_000,
        'note': note,
    }


def cases(rng):
    """Разбор случаев: посчитать по частям и сложить."""
    boys = rng.choice([5, 6, 7])
    girls = rng.choice([3, 4])
    take = rng.choice([4, 5])
    take = min(take, boys + girls - 1)
    least = rng.choice([2, 2, 3])
    least = min(least, girls)
    answer = sum(comb(girls, g) * comb(boys, take - g)
                 for g in range(least, min(girls, take) + 1))
    return {
        'prompt': (f'В группе {_n(boys, BOY)} и {_n(girls, GIRL)}. '
                   f'Выбирают {_n(take, PERSON)} так, чтобы среди них '
                   f'было не меньше ${least}$ девочек. Сколькими '
                   f'способами это можно сделать?'),
        'answer': answer,
        'check': num_check(answer, sf=6),
        'budget_ms': 90_000,
        'note': ('Случаи — по числу девочек в выборке, и они не '
                 'пересекаются: девочек либо столько, либо столько. '
                 'Проверять надо две вещи: что случаи не налезают друг '
                 'на друга и что вместе они покрывают всё. Тот же ответ '
                 'даёт дополнение — всё минус случаи, которые не годятся.'),
    }


def unknown_n(rng):
    """Буква внутри счёта: составить уравнение и отбросить лишний корень."""
    take = rng.choice([2, 2, 3])
    n = rng.choice([6, 7, 8, 9, 10])
    given = comb(n, take)
    sign = '\\mathrm{C}'
    return {
        'prompt': (f'Из $n$ различных предметов выбирают ${take}$, и '
                   f'порядок не важен. Известно, что сделать это можно '
                   f'${given}$ способами, то есть $^n{sign}_{take} = '
                   f'{given}$. Найдите $n$.'),
        'answer': n,
        'check': num_check(n, sf=6),
        'budget_ms': 120_000,
        'note': ('Факториалы не раскрывают, а сокращают: ⁿC₂ = n(n−1)/2, '
                 'ⁿC₃ = n(n−1)(n−2)/6, и уравнение получается '
                 'многочленом. У него бывает второй корень — '
                 'отрицательный или меньший, чем число выбираемых '
                 'предметов, — и его отбрасывают за то, что он '
                 'противоречит условию задачи, а не арифметике.'),
    }


